#!/usr/bin/env bash
# Attach a one-shot, recursively re-arming none_dealloc watchdog to a running
# legacy train job. Static train settings are passed through environment vars.
set -euo pipefail

REPO=${REPO:-/project/peilab/atst/nimloth}
SCRIPTDIR=${REPO}/experiments/training/baseline
SBATCH_BIN=${SBATCH_BIN:-sbatch}
PREVIOUS_JOB_ID=${PREVIOUS_JOB_ID:?set PREVIOUS_JOB_ID}
PREVIOUS_RUN_DIR=${PREVIOUS_RUN_DIR:?set PREVIOUS_RUN_DIR}
RETRY_ROOT_DIR=${RETRY_ROOT_DIR:?set RETRY_ROOT_DIR}
SERVICE_BASE_URL=${SERVICE_BASE_URL:?set SERVICE_BASE_URL}
TRAIN_CONFIG=${TRAIN_CONFIG:?set TRAIN_CONFIG}
VAL_CONFIG=${VAL_CONFIG:?set VAL_CONFIG}
ACTOR_MODEL_PATH=${ACTOR_MODEL_PATH:?set ACTOR_MODEL_PATH}
CRITIC_MODEL_PATH=${CRITIC_MODEL_PATH:-${ACTOR_MODEL_PATH}}

RETRY_BASENAME=${RETRY_BASENAME:-vagen_legacy_auto_resume}
RETRY_INDEX=${RETRY_INDEX:-1}
MAX_AUTO_RETRIES=${MAX_AUTO_RETRIES:-8}
TARGET_STEP=${TARGET_STEP:-330}
TRAIN_PARTITION=${TRAIN_PARTITION:-preempt}
TRAIN_GPUS_PER_NODE=${TRAIN_GPUS_PER_NODE:-8}
TRAIN_NODES=${TRAIN_NODES:-1}
TRAIN_CPUS_PER_TASK=${TRAIN_CPUS_PER_TASK:-128}
TRAIN_MEM=${TRAIN_MEM:-512G}
RAY_NUM_CPUS=${RAY_NUM_CPUS:-128}
TOTAL_EPOCHS=${TOTAL_EPOCHS:-30}
TEST_FREQ=${TEST_FREQ:-10}
SAVE_FREQ=${SAVE_FREQ:-1}
ENABLE_WANDB=${ENABLE_WANDB:-1}
ROLLOUT_MAX_TURNS=${ROLLOUT_MAX_TURNS:-20}
VLLM_MAX_RESPONSE_PER_TURN=${VLLM_MAX_RESPONSE_PER_TURN:-1024}
VAGEN_NON_RESPONSE_TOKEN_RESERVE=${VAGEN_NON_RESPONSE_TOKEN_RESERVE:-11000}
ROLLOUT_MAX_TRAJECTORY_LENGTH=${ROLLOUT_MAX_TRAJECTORY_LENGTH:-32000}
VAGEN_TRAJECTORY_TRUNCATION=${VAGEN_TRAJECTORY_TRUNCATION:-error}
RESTORE_DATALOADER_STATE=${RESTORE_DATALOADER_STATE:-true}

EXPORTS="ALL,REPO=${REPO},PREVIOUS_JOB_ID=${PREVIOUS_JOB_ID},PREVIOUS_RUN_DIR=${PREVIOUS_RUN_DIR},RETRY_ROOT_DIR=${RETRY_ROOT_DIR},RETRY_BASENAME=${RETRY_BASENAME},RETRY_INDEX=${RETRY_INDEX},MAX_AUTO_RETRIES=${MAX_AUTO_RETRIES},TARGET_STEP=${TARGET_STEP},SERVICE_BASE_URL=${SERVICE_BASE_URL},TRAIN_CONFIG=${TRAIN_CONFIG},VAL_CONFIG=${VAL_CONFIG},ACTOR_MODEL_PATH=${ACTOR_MODEL_PATH},CRITIC_MODEL_PATH=${CRITIC_MODEL_PATH},TRAIN_PARTITION=${TRAIN_PARTITION},TRAIN_GPUS_PER_NODE=${TRAIN_GPUS_PER_NODE},TRAIN_NODES=${TRAIN_NODES},TRAIN_CPUS_PER_TASK=${TRAIN_CPUS_PER_TASK},TRAIN_MEM=${TRAIN_MEM},RAY_NUM_CPUS=${RAY_NUM_CPUS},TOTAL_EPOCHS=${TOTAL_EPOCHS},TEST_FREQ=${TEST_FREQ},SAVE_FREQ=${SAVE_FREQ},ENABLE_WANDB=${ENABLE_WANDB},ROLLOUT_MAX_TURNS=${ROLLOUT_MAX_TURNS},VLLM_MAX_RESPONSE_PER_TURN=${VLLM_MAX_RESPONSE_PER_TURN},VAGEN_NON_RESPONSE_TOKEN_RESERVE=${VAGEN_NON_RESPONSE_TOKEN_RESERVE},ROLLOUT_MAX_TRAJECTORY_LENGTH=${ROLLOUT_MAX_TRAJECTORY_LENGTH},VAGEN_TRAJECTORY_TRUNCATION=${VAGEN_TRAJECTORY_TRUNCATION},RESTORE_DATALOADER_STATE=${RESTORE_DATALOADER_STATE},SBATCH_BIN=${SBATCH_BIN}"

WATCHDOG_JOB_ID=$("${SBATCH_BIN}" --parsable \
  --dependency="afternotok:${PREVIOUS_JOB_ID}" --kill-on-invalid-dep=yes \
  --export="${EXPORTS}" \
  "${SCRIPTDIR}/legacy_train_failure_watchdog.slurm")
WATCHDOG_JOB_ID=${WATCHDOG_JOB_ID%%;*}
echo "${WATCHDOG_JOB_ID}"
