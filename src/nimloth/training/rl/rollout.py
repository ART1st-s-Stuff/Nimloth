@dataclass
class RolloutTrajectory:
    """One exact policy/environment transcript.

    Images and observation texts have length ``num_steps + 1``.  Every other
    per-step list has length ``num_steps``.  Keeping the generated assistant
    response and VAGEN reward at their original turn prevents PPO/WM replay
    from silently constructing a different prompt or reward sequence.
    """

    record_id: str
    image_paths: list[str] = field(default_factory=list)
    observation_texts: list[str] = field(default_factory=list)
    task_instruction: str = ""
    system_prompt: str = ""
    assistant_responses: list[str] = field(default_factory=list)
    action_indices: list[int] = field(default_factory=list)
    action_names: list[str] = field(default_factory=list)
    action_log_probs: list[list[float]] = field(default_factory=list)
    step_rewards: list[float] = field(default_factory=list)
    final_reward: float = 0.0
    success: bool = False
    reward: float = 0.0
    split: str = "train"
    latent_token_count: int = 1

    @property
    def num_steps(self) -> int:
        return len(self.action_indices)

    @property
    def messages(self) -> list[dict[str, str]]:
        """Return only turns actually consumed/generated by the policy.

        The final observation is retained for environment/WM alignment, but no
        assistant action was requested from it and it is therefore not appended
        as a trailing user message.
        """

        messages = [{"role": "system", "content": self.system_prompt}]
        for observation, response in zip(
            self.observation_texts[:-1], self.assistant_responses
        ):
            messages.append({"role": "user", "content": observation})
            messages.append({"role": "assistant", "content": response})
        return messages

    def to_record(self) -> dict[str, Any]:
        """Serialize the lossless trajectory protocol."""
        return {
            "id": self.record_id,
            "split": self.split,
            "success": self.success,
            "reward": self.reward,
            "final_reward": self.final_reward,
            "step_rewards": self.step_rewards,
            "system_prompt": self.system_prompt,
            "task_instruction": self.task_instruction,
            "observation_texts": self.observation_texts,
            "assistant_responses": self.assistant_responses,
            "messages": self.messages,
            "image_paths": self.image_paths,
            "action_indices": self.action_indices,
            "action_names": self.action_names,
            "action_log_probs": self.action_log_probs,
            "latent_token_count": self.latent_token_count,
        }

    @classmethod
    def from_record(cls, record: dict[str, Any]) -> "RolloutTrajectory":
        required = (
            "system_prompt",
            "task_instruction",
            "observation_texts",
            "assistant_responses",
            "step_rewards",
        )
        missing = [key for key in required if key not in record]
        if missing:
            raise ValueError(
                "legacy/taskless rollout record is not valid for RL replay; "
                f"missing={missing}"
            )
        return cls(
            record_id=str(record.get("id", "")),
            image_paths=list(record.get("image_paths", [])),
            observation_texts=[str(value) for value in record["observation_texts"]],
            task_instruction=str(record["task_instruction"]),
            system_prompt=str(record["system_prompt"]),
            assistant_responses=[str(value) for value in record["assistant_responses"]],
            action_indices=[int(value) for value in record.get("action_indices", [])],
            action_names=[str(value) for value in record.get("action_names", [])],
            action_log_probs=list(record.get("action_log_probs", [])),
            step_rewards=[float(value) for value in record["step_rewards"]],
            final_reward=float(record.get("final_reward", 0.0)),
            success=bool(record.get("success", False)),
            reward=float(record.get("reward", 0.0)),
            split=str(record.get("split", "train")),
            latent_token_count=int(record.get("latent_token_count", 1)),
        )


