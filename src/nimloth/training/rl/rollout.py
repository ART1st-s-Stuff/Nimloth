class EnvRolloutCollector:
    """Collect trajectories by running Qwen policy against the VAGEN env server.

    Reuses the trainer's Qwen model (no subprocess/model-reloading).
    Each ``collect()`` call creates envs on the server, runs Qwen-based
    greedy action selection, and returns ``RolloutTrajectory`` objects.
    """

    def __init__(
        self,
        qwen_model,
        processor,
        env_url: str,
        device,
        seed_offset: int = 0,
        temperature: float = 1.0,
        top_p: float = 1.0,
        eval_sets: tuple[str, ...] = ("base", "common_sense"),
        split: str = "eval",
        history_window: int = 112,
        env_timeout: int = 180,
        latent_token_count: int = 1,
        max_think_tokens: int = 512,
    ) -> None:
        if not eval_sets:
            raise ValueError("EnvRolloutCollector requires at least one eval_set")
        if split == "train" and any(not name.endswith("_train") for name in eval_sets):
            raise ValueError(
                "training rollout requires *_train datasets; "
                f"got eval_sets={eval_sets}"
            )
        if split == "validation" and any(name.endswith("_train") for name in eval_sets):
            raise ValueError(
                "heldout validation forbids *_train datasets; "
                f"got eval_sets={eval_sets}"
            )
        self._model = qwen_model
        self._processor = processor
        self._env_url = env_url.rstrip("/")
        self._device = device
        self._base_seed_offset = int(seed_offset)
        self._ep_counter = int(seed_offset)
        self._client = None  # lazy init
        self._temperature = temperature
        self._top_p = top_p
        self._eval_sets = eval_sets
        self._split = split
        if latent_token_count < 1:
            raise ValueError(
                f"latent_token_count must be >= 1, got {latent_token_count}"
            )
        self._latent_token_count = int(latent_token_count)
        if history_window < 0:
            raise ValueError(f"history_window must be >= 0, got {history_window}")
        self._history_window = int(history_window)
        if env_timeout <= 0:
            raise ValueError(f"env_timeout must be > 0, got {env_timeout}")
        self._env_timeout = int(env_timeout)
        if max_think_tokens <= 0:
            raise ValueError(f"max_think_tokens must be > 0, got {max_think_tokens}")
        self._max_think_tokens = int(max_think_tokens)

    @property
    def client(self):
        if self._client is None:
            from vagen.server.client import BatchEnvClient
            self._client = BatchEnvClient(
                base_url=self._env_url, timeout=self._env_timeout
            )
        return self._client

    def _environment_config(self, eval_set: str) -> dict[str, Any]:
        """Return the pinned source_eval_mode SFT-collection environment."""

        return {
            "env_name": "navigation",
            "env_config": {
                "render_mode": "vision",
                "prompt_format": "source_eval_mode",
                "use_state_reward": False,
                "eval_set": eval_set,
                "max_actions_per_step": 1,
                "action_sep": "|",
                "example_count": 0,
                "format_reward": 0.0,
                "per_turn_format_reward": 0.01,
                "success_reward": 1.0,
                "success_threshold": 1.0,
                "step_length": 0.3,
                "grounding_reward_weight": 0.5,
                "worldmodeling_reward_weight": 0.5,
                "gpu_device": 0,
            },
        }

    def _sampling_seed(self, episode_seed: int, step: int) -> int:
        # Sampling is a pure function of env seed + step, so checkpoint resume
        # does not depend on a process-local RNG state.
        return int((self._base_seed_offset + 1) * 1_000_003 + episode_seed * 997 + step)

    def reset_seed_cursor(self) -> None:
        """Reset to the fixed base seed (used for repeatable heldout evaluation)."""

        self._ep_counter = self._base_seed_offset

    def set_resume_iteration(
        self,
        *,
        start_iteration: int,
        envs_per_iteration: int,
        validation_enabled: bool,
        validation_interval: int,
        validation_envs: int,
    ) -> None:
        """Restore the deterministic environment-seed cursor for resume."""

        completed = max(0, int(start_iteration) - 1)
        consumed = completed * int(envs_per_iteration)
        if validation_enabled and validation_interval > 0:
            consumed += (completed // int(validation_interval)) * int(validation_envs)
        self._ep_counter = self._base_seed_offset + consumed

    def collect(
        self,
        *,
        num_episodes: int,
        max_steps_per_episode: int = 20,
        output_dir: Path | None = None,
    ) -> list[RolloutTrajectory]:

        out_dir = output_dir or Path(".")
        out_dir.mkdir(parents=True, exist_ok=True)
        img_dir = out_dir / "images"
        img_dir.mkdir(parents=True, exist_ok=True)
        print(json.dumps({"rl_collect": "start", "num_episodes": num_episodes,
                          "output": str(out_dir)}), flush=True)

        # --- lazy-init client -------------------------------------------------
        if self._client is None:
            print(json.dumps({"rl_collect": "init_client", "url": self._env_url}), flush=True)
            try:
                from vagen.server.client import BatchEnvClient
                self._client = BatchEnvClient(
                    base_url=self._env_url, timeout=self._env_timeout
                )
                print(json.dumps({"rl_collect": "client_created"}), flush=True)
            except Exception:
                import traceback
                traceback.print_exc()
                print(json.dumps({"rl_collect": "client_init_failed"}), flush=True)
                raise

        trajectories: list[RolloutTrajectory] = []

        for ep_i in range(num_episodes):
            seed = self._ep_counter
            ep_id = f"rl_{seed:06d}"
            self._ep_counter += 1
            t0 = time.time()
            eval_set = self._eval_sets[ep_i % len(self._eval_sets)]

            print(json.dumps({"rl_ep": ep_i, "id": ep_id, "eval_set": eval_set}), flush=True)

            env_config = self._environment_config(eval_set)

            # --- create env on server ---
            print(json.dumps({"rl_ep": ep_i, "step": "create_env"}), flush=True)
            try:
                self._client.create_environments_batch({ep_id: env_config})
                print(json.dumps({"rl_ep": ep_i, "step": "create_env_done"}), flush=True)
            except Exception:
                import traceback
                traceback.print_exc()
                print(json.dumps({"rl_ep": ep_i, "step": "create_env_failed",
                                  "error": str(traceback.format_exc())}), flush=True)
                continue

            # --- get system prompt ---
            print(json.dumps({"rl_ep": ep_i, "step": "get_prompt"}), flush=True)
            try:
                from nimloth.training.rl.vagen_protocol import source_eval_text_to_nimloth

                prompts = self._client.get_system_prompts_batch([ep_id])
                raw_system_prompt = str(prompts.get(ep_id, "")).strip()
                if not raw_system_prompt:
                    raise RuntimeError(f"environment returned no system prompt for {ep_id}")
                system_prompt = source_eval_text_to_nimloth(
                    raw_system_prompt,
                    latent_token_count=self._latent_token_count,
                )
                print(json.dumps({"rl_ep": ep_i, "step": "get_prompt_done"}), flush=True)
            except Exception:
                import traceback
                traceback.print_exc()
                try:
                    self._client.close_batch([ep_id])
                except Exception:
                    pass
                continue

            # --- reset ---
            print(json.dumps({"rl_ep": ep_i, "step": "reset", "seed": seed}), flush=True)
            try:
                results = self._client.reset_batch({ep_id: seed})
                obs, info = results[ep_id]
                print(json.dumps({"rl_ep": ep_i, "step": "reset_done"}), flush=True)
            except Exception:
                import traceback
                traceback.print_exc()
                print(json.dumps({"rl_ep": ep_i, "step": "reset_failed",
                                  "error": str(traceback.format_exc())}), flush=True)
                try:
                    self._client.close_batch([ep_id])
                except Exception:
                    pass
                continue

            action_names: list[str] = []
            action_indices: list[int] = []
            action_log_probs: list[list[float]] = []
            assistant_responses: list[str] = []
            image_paths: list[str] = []
            observation_texts: list[str] = []
            task_instruction = ""
            done = False
            step_rewards: list[float] = []
            success = False
            episode_valid = True

            for step in range(max_steps_per_episode):
                print(json.dumps({"rl_ep": ep_i, "step": f"action_{step}", "history_len": len(action_names)}), flush=True)

                # VAGEN owns both the image and the policy-visible text.
                try:
                    from nimloth.training.rl.vagen_protocol import (
                        extract_human_instruction,
                        nimloth_assistant_response,
                        observation_text_and_image,
                        task_succeeded,
                        vagen_env_response,
                    )

                    observation_text, img = observation_text_and_image(
                        obs, latent_token_count=self._latent_token_count
                    )
                    if not observation_texts:
                        task_instruction = extract_human_instruction(observation_text)
                except Exception:
                    import traceback
                    traceback.print_exc()
                    episode_valid = False
                    break

                img_path = img_dir / f"{ep_id}_step{step:02d}.png"
                img.save(str(img_path))
                image_paths.append(str(img_path))
                observation_texts.append(observation_text)

                try:
                    generator = torch.Generator(device="cpu")
                    generator.manual_seed(self._sampling_seed(seed, step))
                    thought, action_name, action_idx, log_probs_list = _select_action_nimloth(
                        self._model,
                        self._processor,
                        image_paths,
                        system_prompt,
                        observation_texts,
                        assistant_responses,
                        temperature=self._temperature,
                        top_p=self._top_p,
                        history_window=self._history_window,
                        latent_token_count=self._latent_token_count,
                        max_think_tokens=self._max_think_tokens,
                        generator=generator,
                    )
                    assistant_response = nimloth_assistant_response(
                        thought,
                        action_idx,
                        latent_token_count=self._latent_token_count,
                    )
                    env_response = vagen_env_response(thought, action_idx)
                    print(json.dumps({"rl_ep": ep_i, "action_selected": action_name,
                                      "action_idx": action_idx}), flush=True)
                except Exception:
                    import traceback
                    traceback.print_exc()
                    episode_valid = False
                    break

                try:
                    step_results = self._client.step_batch({ep_id: env_response})
                    obs, r, done, info = step_results[ep_id]
                    if not isinstance(info, dict) or str(info.get("instruction", "")) != task_instruction:
                        raise RuntimeError(
                            "environment task changed or disagrees with initial observation: "
                            f"initial={task_instruction!r}, step_info="
                            f"{info.get('instruction') if isinstance(info, dict) else None!r}"
                        )
                    step_rewards.append(float(r))
                    success = success or task_succeeded(info)
                    action_ok = info.get("last_action_success", True) if isinstance(info, dict) else True
                    print(json.dumps({"rl_ep": ep_i, "env_step_done": True, "done": done,
                                      "step_reward": r, "action_ok": action_ok}), flush=True)
                except Exception:
                    import traceback
                    traceback.print_exc()
                    episode_valid = False
                    break

                action_names.append(action_name)
                action_indices.append(action_idx)
                action_log_probs.append(log_probs_list)
                assistant_responses.append(assistant_response)

                if done:
                    break

            final_reward = 0.0
            try:
                from nimloth.training.rl.vagen_protocol import observation_text_and_image

                final_text, final_img = observation_text_and_image(
                    obs, latent_token_count=self._latent_token_count
                )
                img_path = img_dir / f"{ep_id}_step{len(action_names):02d}.png"
                final_img.save(str(img_path))
                image_paths.append(str(img_path))
                observation_texts.append(final_text)
                rewards = self._client.compute_reward_batch([ep_id])
                if ep_id not in rewards:
                    raise RuntimeError(f"environment returned no final reward for {ep_id}")
                final_reward = float(rewards[ep_id])
            except Exception:
                import traceback
                traceback.print_exc()
                episode_valid = False

            reward = sum(step_rewards) + final_reward

            try:
                self._client.close_batch([ep_id])
            except Exception:
                pass

            if not episode_valid or not action_names or len(image_paths) != len(action_names) + 1:
                print(json.dumps({
                    "rl_ep": ep_i,
                    "warning": "discarding incomplete trajectory",
                    "num_actions": len(action_names),
                    "num_images": len(image_paths),
                }), flush=True)
                continue

            trajectory = RolloutTrajectory(
                record_id=ep_id,
                image_paths=image_paths,
                observation_texts=observation_texts,
                task_instruction=task_instruction,
                system_prompt=system_prompt,
                assistant_responses=assistant_responses,
                action_indices=action_indices,
                action_names=list(action_names),
                action_log_probs=action_log_probs,
                step_rewards=step_rewards,
                final_reward=final_reward,
                success=success,
                reward=reward,
                split=self._split,
                latent_token_count=self._latent_token_count,
            )
            validate_rollout_trajectory(trajectory)
            trajectories.append(trajectory)

            elapsed = time.time() - t0
            print(json.dumps({
                "rl_ep": ep_i, "done": True,
                "steps": len(action_names),
                "success": success,
                "reward": round(reward, 2),
                "elapsed_s": round(elapsed, 1),
            }), flush=True)

        jsonl_path = save_trajectories(trajectories, out_dir)
        print(json.dumps({
            "rl_collect": "done",
            "trajectories": len(trajectories),
            "jsonl_path": str(jsonl_path),
        }), flush=True)
        return trajectories


