def sample_action_from_logits(
    action_logits: torch.Tensor,
    *,
    temperature: float,
    top_p: float,
    generator: torch.Generator | None = None,
) -> tuple[int, list[float]]:
    """Sample one action and return temperature-scaled full log-probs.

    Top-p only restricts sampling.  PPO log-probs use the full temperature-scaled
    distribution, matching VAGEN/VERL's recompute-log-prob convention.
    """

    if action_logits.shape != (len(ACTION_NAMES),):
        raise ValueError(f"expected 8 action logits, got {tuple(action_logits.shape)}")
    if temperature < 0:
        raise ValueError(f"temperature must be >= 0, got {temperature}")
    if not 0 < top_p <= 1:
        raise ValueError(f"top_p must be in (0, 1], got {top_p}")

    logits = action_logits.detach().float().cpu()
    if temperature == 0:
        chosen_idx = int(logits.argmax().item())
        log_probs = torch.log_softmax(logits, dim=-1)
        return chosen_idx, [float(value) for value in log_probs.tolist()]

    scaled = logits / temperature
    log_probs = torch.log_softmax(scaled, dim=-1)
    sampling_logits = scaled.clone()
    if top_p < 1.0:
        sorted_logits, sorted_indices = torch.sort(sampling_logits, descending=True)
        sorted_probs = torch.softmax(sorted_logits, dim=-1)
        cumulative_before = torch.cumsum(sorted_probs, dim=-1) - sorted_probs
        keep = cumulative_before < top_p
        keep[0] = True
        keep_mask = torch.zeros_like(sampling_logits, dtype=torch.bool)
        keep_mask[sorted_indices[keep]] = True
        sampling_logits[~keep_mask] = float("-inf")
    probabilities = torch.softmax(sampling_logits, dim=-1)
    chosen_idx = int(torch.multinomial(probabilities, 1, generator=generator).item())
    return chosen_idx, [float(value) for value in log_probs.tolist()]


def sample_token_from_logits(
    logits: torch.Tensor,
    *,
    temperature: float,
    top_p: float,
    generator: torch.Generator | None = None,
) -> int:
    """Sample one vocabulary token with the rollout temperature/top-p rules."""

    if logits.ndim != 1:
        raise ValueError(f"expected one-dimensional token logits, got {tuple(logits.shape)}")
    if temperature < 0:
        raise ValueError(f"temperature must be >= 0, got {temperature}")
    if not 0 < top_p <= 1:
        raise ValueError(f"top_p must be in (0, 1], got {top_p}")
    values = logits.detach().float().cpu()
    if temperature == 0:
        return int(values.argmax().item())
    values = values / temperature
    if top_p < 1.0:
        sorted_logits, sorted_indices = torch.sort(values, descending=True)
        sorted_probs = torch.softmax(sorted_logits, dim=-1)
        cumulative_before = torch.cumsum(sorted_probs, dim=-1) - sorted_probs
        keep = cumulative_before < top_p
        keep[0] = True
        mask = torch.zeros_like(values, dtype=torch.bool)
        mask[sorted_indices[keep]] = True
        values[~mask] = float("-inf")
    return int(torch.multinomial(
        torch.softmax(values, dim=-1), 1, generator=generator
    ).item())


def _select_action_nimloth(
    model,
    processor,
    image_history: list[Any],
    system_prompt: str,
    observation_texts: list[str],
    assistant_responses: list[str],
    *,
    temperature: float = 1.0,
    top_p: float = 1.0,
    history_window: int = 112,
    latent_token_count: int = 1,
    max_think_tokens: int = 512,
    generator: torch.Generator | None = None,
) -> tuple[str, str, int, list[float]]:
    """Generate the actual assistant thought, inject queries, and sample action."""

    thought, action_logits = generate_nimloth_thought_and_action_logits(
        model,
        processor,
        image_history,
        system_prompt,
        observation_texts,
        assistant_responses,
        history_window=history_window,
        latent_token_count=latent_token_count,
        max_think_tokens=max_think_tokens,
        token_selector=lambda logits, _: sample_token_from_logits(
            logits,
            temperature=temperature,
            top_p=top_p,
            generator=generator,
        ),
    )
    chosen_idx, log_probs = sample_action_from_logits(
        action_logits,
        temperature=temperature,
        top_p=top_p,
        generator=generator,
    )
    return thought, ACTION_NAMES[chosen_idx], chosen_idx, log_probs


def validate_rollout_trajectory(trajectory: RolloutTrajectory) -> None:
    """Reject lossy, taskless, or numerically invalid policy trajectories."""

    from nimloth.training.rl.vagen_protocol import (
        ACTION_NAME_TO_IDX,
        extract_human_instruction,
        nimloth_assistant_response,
    )

    steps = trajectory.num_steps
    if steps <= 0:
        raise ValueError(f"trajectory {trajectory.record_id!r} has no actions")
    lengths = {
        "images": len(trajectory.image_paths),
        "observation_texts": len(trajectory.observation_texts),
    }
    for name, length in lengths.items():
        if length != steps + 1:
            raise ValueError(
                f"trajectory {trajectory.record_id!r}: {name}={length} but actions={steps}"
            )
    per_step = {
        "action_names": len(trajectory.action_names),
        "action_log_probs": len(trajectory.action_log_probs),
        "assistant_responses": len(trajectory.assistant_responses),
        "step_rewards": len(trajectory.step_rewards),
    }
    for name, length in per_step.items():
        if length != steps:
            raise ValueError(
                f"trajectory {trajectory.record_id!r}: {name}={length} but actions={steps}"
            )
    if not trajectory.system_prompt.strip():
        raise ValueError(f"trajectory {trajectory.record_id!r} has no system prompt")
    extracted_instruction = extract_human_instruction(trajectory.observation_texts[0])
    if trajectory.task_instruction != extracted_instruction:
        raise ValueError(
            f"trajectory {trajectory.record_id!r}: task_instruction does not match "
            "the initial environment observation"
        )
    for index, text in enumerate(trajectory.observation_texts):
        if text.count("<image>") != 1:
            raise ValueError(
                f"trajectory {trajectory.record_id!r}: observation {index} must have one <image>"
            )
    for step, (action_idx, action_name, log_probs, response, step_reward) in enumerate(zip(
        trajectory.action_indices,
        trajectory.action_names,
        trajectory.action_log_probs,
        trajectory.assistant_responses,
        trajectory.step_rewards,
    )):
        if not 0 <= int(action_idx) < len(ACTION_NAMES):
            raise ValueError(f"trajectory {trajectory.record_id!r}: invalid action {action_idx}")
        if ACTION_NAME_TO_IDX.get(action_name) != int(action_idx):
            raise ValueError(
                f"trajectory {trajectory.record_id!r}: action name/index mismatch at step {step}"
            )
        if len(log_probs) != len(ACTION_NAMES):
            raise ValueError(
                f"trajectory {trajectory.record_id!r}: step {step} has "
                f"{len(log_probs)} action log-probs"
            )
        if not all(math.isfinite(float(value)) for value in log_probs):
            raise ValueError(
                f"trajectory {trajectory.record_id!r}: step {step} has non-finite log-probs"
            )
        probability_sum = sum(math.exp(float(value)) for value in log_probs)
        if not math.isclose(probability_sum, 1.0, rel_tol=1e-5, abs_tol=1e-5):
            raise ValueError(
                f"trajectory {trajectory.record_id!r}: step {step} action "
                f"log-probs are not normalized (sum={probability_sum})"
            )
        if not math.isfinite(float(step_reward)):
            raise ValueError(
                f"trajectory {trajectory.record_id!r}: step {step} has non-finite reward"
            )
        thought_end = response.find("</think>")
        if thought_end < 0:
            raise ValueError(
                f"trajectory {trajectory.record_id!r}: step {step} has no complete thought"
            )
        thought = response[:thought_end + len("</think>")]
        expected = nimloth_assistant_response(
            thought,
            int(action_idx),
            latent_token_count=trajectory.latent_token_count,
        )
        if response != expected:
            raise ValueError(
                f"trajectory {trajectory.record_id!r}: step {step} assistant response "
                "does not match the inject training format"
            )
    if not math.isfinite(float(trajectory.final_reward)):
        raise ValueError(f"trajectory {trajectory.record_id!r} has non-finite final reward")
    expected_total = sum(float(value) for value in trajectory.step_rewards) + float(
        trajectory.final_reward
    )
    if not math.isclose(float(trajectory.reward), expected_total, abs_tol=1e-6):
        raise ValueError(
            f"trajectory {trajectory.record_id!r}: reward={trajectory.reward} but "
            f"step/final total={expected_total}"
        )


